/**
 * Every sentence the app shows, in English and Dutch. Shared by server and
 * client: pages call `translator(profile.locale)`, client components get the
 * locale from `LocaleProvider` (src/components/locale.tsx).
 *
 * `nl` is typed against `en`, so a key missing in one language fails the
 * typecheck rather than showing up blank on a phone. Plurals are two keys,
 * `x.one` and `x.other`, picked by `t.count`.
 */

export type Locale = "en" | "nl";
export const LOCALES: readonly Locale[] = ["en", "nl"];
export const DEFAULT_LOCALE: Locale = "en";

export function isLocale(value: unknown): value is Locale {
  return value === "en" || value === "nl";
}

