const MESSAGES: Record<Locale, Record<MessageKey, string>> = { en, nl };

type Vars = Record<string, string | number>;

function fill(text: string, vars?: Vars) {
  if (!vars) return text;
  return text.replace(/\{(\w+)\}/g, (match, name) => (name in vars ? String(vars[name]) : match));
}

export type Translate = {
  (key: MessageKey, vars?: Vars): string;
  /** Picks `${key}.one` or `${key}.other` by `n`, with `{n}` filled in. */
  count: (key: string, n: number, vars?: Vars) => string;
  locale: Locale;
};

export function translator(locale: Locale): Translate {
  const messages = MESSAGES[locale] ?? en;
  const t = ((key: MessageKey, vars?: Vars) => fill(messages[key] ?? en[key] ?? key, vars)) as Translate;
  t.count = (key, n, vars) => t(`${key}.${n === 1 ? "one" : "other"}` as MessageKey, { n, ...vars });
  t.locale = locale;
  return t;
}

/** Category label by key, singular or plural, in the right language. */
export function categoryLabel(t: Translate, category: string, form: "one" | "other" = "one") {
  const key = `category.${category}.${form}` as MessageKey;
  return key in en ? t(key) : category;
}

export function formalityLabel(t: Translate, level: number) {
  const key = `formality.${level}` as MessageKey;
  return key in en ? t(key) : "";
}

/** "August", or "August 2025" when it was not this year. Dutch months stay lowercase, as they are mid-sentence. */
export function monthName(date: Date, now: Date, locale: Locale) {
  const name = date.toLocaleString(INTL_TAG[locale], { month: "long" });
  return date.getFullYear() === now.getFullYear() ? name : `${name} ${date.getFullYear()}`;
}

export function capitalise(text: string) {
  return text.charAt(0).toUpperCase() + text.slice(1);
}

/** "14 March", or with the year when it was not this year. */
export function shortDate(date: Date, now: Date, locale: Locale) {
  return date.toLocaleDateString(INTL_TAG[locale], {
    day: "numeric",
    month: "long",
    year: date.getFullYear() === now.getFullYear() ? undefined : "numeric",
  });
}

/** The language a browser asks for, used before a profile has chosen one. */
export function localeFromAcceptLanguage(header: string | null | undefined): Locale {
  if (!header) return DEFAULT_LOCALE;
  const first = header.split(",")[0]?.trim().toLowerCase() ?? "";
  return first.startsWith("nl") ? "nl" : DEFAULT_LOCALE;
}
